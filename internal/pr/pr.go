// Package pr abstracts pull-request hosting. Providers register themselves by
// config name.
package pr

import (
	"context"
	"fmt"
	"sort"
	"strings"
	"sync"

	"github.com/bengearig/ralph/internal/config"
	"github.com/bengearig/ralph/internal/service"
)

// Request describes a pull request to open.
type Request struct {
	Title             string `json:"title"`
	Body              string `json:"body"`
	SourceBranch      string `json:"source_branch"`
	DestinationBranch string `json:"destination_branch"`
	Draft             bool   `json:"draft"`
}

// PullRequest is an opened pull request.
type PullRequest struct {
	ID         string `json:"id"`
	Namespace  string `json:"namespace"`
	Repository string `json:"repository"`
	Number     int    `json:"number"`
	URL        string `json:"url"`
}

// Provider opens pull requests on a hosting service.
type Provider interface {
	Name() string
	// Validate checks configuration and credentials without network calls.
	Validate() error
	Create(ctx context.Context, req Request) (PullRequest, error)
	// FindOpen returns the most recently updated open pull request from
	// sourceBranch into destinationBranch, or false when there is none.
	FindOpen(ctx context.Context, sourceBranch, destinationBranch string) (PullRequest, bool, error)
}

// Factory builds a provider from configuration.
type Factory func(cfg *config.Config) (Provider, error)

var (
	mu        sync.RWMutex
	factories = map[string]Factory{}
)

// Register makes a provider available under name.
func Register(name string, f Factory) {
	mu.Lock()
	defer mu.Unlock()
	if _, dup := factories[name]; dup {
		panic("pr: duplicate registration of " + name)
	}
	factories[name] = f
}

// LinkFunc builds a pull request's web URL from static identifiers alone.
type LinkFunc func(namespace, repository string, number int) string

var links = map[string]LinkFunc{}

// RegisterLink makes a provider's link builder available under name.
func RegisterLink(provider string, f LinkFunc) {
	mu.Lock()
	defer mu.Unlock()
	if _, dup := links[provider]; dup {
		panic("pr: duplicate link registration of " + provider)
	}
	links[provider] = f
}

// Link returns the web URL of a pull request; false if the provider has no
// registered link builder.
func Link(provider, namespace, repository string, number int) (string, bool) {
	mu.RLock()
	f := links[provider]
	mu.RUnlock()
	if f == nil {
		return "", false
	}
	return f(namespace, repository, number), true
}

// New builds the configured provider.
func New(cfg *config.Config) (Provider, error) {
	mu.RLock()
	f, ok := factories[cfg.PR.Provider]
	mu.RUnlock()
	if !ok {
		names := make([]string, 0, len(factories))
		for n := range factories {
			names = append(names, n)
		}
		sort.Strings(names)
		return nil, fmt.Errorf("unknown pull request provider %q (registered: %v)", cfg.PR.Provider, names)
	}
	return f(cfg)
}

// MilestoneRequest describes a milestone's pull request: the milestone title,
// a summary of its tasks, and a pointer back to the initiative.
func MilestoneRequest(cfg *config.Config, initiative service.InitiativeView, milestone service.MilestoneView, tasks []service.TaskView, branch string) Request {
	var b strings.Builder
	fmt.Fprintf(&b, "Milestone %s of initiative %s (%s).\n", milestone.ID, initiative.ID, initiative.Title)
	if milestone.Description != "" {
		fmt.Fprintf(&b, "\n%s\n", milestone.Description)
	}
	b.WriteString("\n## Tasks\n\n")
	for _, t := range tasks {
		box := " "
		if t.Status == "DONE" {
			box = "x"
		}
		fmt.Fprintf(&b, "- [%s] %s %s (%s)\n", box, t.ID, t.Title, t.Status)
	}
	b.WriteString("\nGenerated by ralph. Agents propose; people merge.\n")
	return Request{
		Title:             fmt.Sprintf("%s: %s", milestone.ID, milestone.Title),
		Body:              b.String(),
		SourceBranch:      branch,
		DestinationBranch: cfg.PR.BaseBranch,
		Draft:             cfg.PR.Draft,
	}
}
